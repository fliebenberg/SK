#!/usr/bin/env node
/**
 * Generates the server's action payload check from the payload types (`SYNC-6`).
 *
 * The types in shared/src/types/Protocol.ts are the one definition of what each action takes;
 * `ActionPayloads` maps every action to its payload. This turns that into JSON Schema — every
 * object closed to fields its type does not name — and writes it to src/wss/actionPayloads.schema.json,
 * which src/wss/actionPayloads.ts checks every incoming action against.
 *
 * The output records a hash of shared/src, and `check-action-schemas.js` (run by the pre-commit hook)
 * fails when the types have changed since, so the check cannot quietly drift from the types.
 *
 * Run: `npm run gen:action-schemas` (from server/), after any change to shared/src.
 */
const fs = require('fs');
const path = require('path');
const { createGenerator } = require('ts-json-schema-generator');
const { sharedSourceHash, SCHEMA_FILE } = require('./action-schemas-hash');

const SHARED = path.resolve(__dirname, '../../shared');

const schema = createGenerator({
  path: path.join(SHARED, 'src/types/Protocol.ts'),
  tsconfig: path.join(SHARED, 'tsconfig.json'),
  type: 'ActionPayloads',
  expose: 'none',
  topRef: false,
  additionalProperties: false,
  skipTypeCheck: true,
}).createSchema('ActionPayloads');

// Descriptions are the types' doc comments: useful in the editor, dead weight in the check.
(function strip(node) {
  if (!node || typeof node !== 'object') return;
  delete node.description;
  for (const value of Object.values(node)) strip(value);
})(schema);

const out = {
  $comment: 'Generated by server/scripts/gen-action-schemas.js from shared/src/types/Protocol.ts. Do not edit.',
  sourceHash: sharedSourceHash(),
  actions: schema.properties,
};
fs.writeFileSync(SCHEMA_FILE, JSON.stringify(out, null, 1) + '\n');
console.log(`gen:action-schemas — ${Object.keys(out.actions).length} actions written to ${path.relative(process.cwd(), SCHEMA_FILE)}.`);
